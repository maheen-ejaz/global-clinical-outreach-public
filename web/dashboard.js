window.formatTimestamp = (value, zone = "Asia/Kolkata") => {
  if (!value) return "—";
  const parts = Object.fromEntries(new Intl.DateTimeFormat("en-GB", { timeZone: zone,
    day: "numeric", month: "long", year: "numeric", hour: "2-digit", minute: "2-digit", hourCycle: "h23"
  }).formatToParts(new Date(value)).map(p => [p.type, p.value]));
  const day = Number(parts.day);
  const suffix = day % 100 >= 11 && day % 100 <= 13 ? "th" : ({ 1: "st", 2: "nd", 3: "rd" }[day % 10] || "th");
  return `${parts.month} ${day}${suffix}, ${parts.year}, ${parts.hour}:${parts.minute} ${zone === "Asia/Kolkata" ? "IST" : zone}`;
};

