  const teamRows = () => {
    const v = VIEWS[team.view];
    return v.rows().filter(r => !team.q || v.cols.map(c => csvValue(c, r)).join(" ").toLowerCase().includes(team.q));
  };
  function renderTeam() {
    const v = VIEWS[team.view], rows = teamRows(), shown = v.cols.filter(c => c[1]);
    const table = document.getElementById("teamTable");
    table.replaceChildren(
      el("thead", {}, el("tr", {}, shown.map(c => el("th", { scope: "col", text: c[0] })))),
      el("tbody", {}, rows.length ? rows.map(r => el("tr", {}, shown.map(c => c[1](r))))
        : el("tr", {}, el("td", { colspan: shown.length, class: "none", text: "No matches" }))));
    document.getElementById("teamCount").textContent = `${rows.length} of ${v.rows().length} ${v.label.toLowerCase()}`;
  }
  document.getElementById("teamQ").addEventListener("input", e => { team.q = e.target.value.trim().toLowerCase(); renderTeam(); });
  document.getElementById("teamCsv").onclick = () => {
    const v = VIEWS[team.view];
    const lines = [v.cols.map(c => c[0]), ...teamRows().map(r => v.cols.map(c => csvValue(c, r)))].map(r => r.map(csvCell).join(","));
    const a = el("a", { href: URL.createObjectURL(new Blob([lines.join("\n")], { type: "text/csv" })), download: `${BATCH}-${team.view}.csv` });
    document.body.append(a); a.click(); a.remove();
  };
  renderTeam();
